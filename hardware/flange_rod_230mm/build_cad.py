"""Exact, single-solid xArm flange and hemispherical-tip rod. Units: mm.

Dependencies: cadquery, trimesh, numpy, scipy, matplotlib.
Run: python build_cad.py
Edit parameters.json, then rerun to regenerate STEP, STL, SCAD and the preview.
"""

import json
import math
from pathlib import Path

import cadquery as cq
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt
from matplotlib.patches import Arc, Circle, Polygon
from mpl_toolkits.mplot3d.art3d import Poly3DCollection
import numpy as np
from OCP.Bnd import Bnd_Box
from OCP.BRepBndLib import BRepBndLib
from scipy.integrate import quad
import trimesh


ROOT = Path(__file__).resolve().parent
P = json.loads((ROOT / "parameters.json").read_text())
H = P["overall_length_from_flange_contact_face_mm"]
R = P["plate_diameter_mm"] / 2
T = P["plate_thickness_mm"]
R_ROD = P["rod_diameter_mm"] / 2
STEM = f"xarm_flange_rod_d{2*R_ROD:g}_total{H:g}"
F = P["root_fillet_radius_mm"]
BR = P["mount_pcd_mm"] / 2
HR = P["clearance_diameter_mm"] / 2
CR = P["countersink_diameter_mm"] / 2
HALF_ANGLE = math.radians(P["countersink_angle_deg"] / 2)
SINK_DEPTH = (CR - HR) / math.tan(HALF_ANGLE)
LAND = T - SINK_DEPTH
HEMISPHERE_EQUATOR_Z = H - R_ROD
STRAIGHT_LENGTH_FROM_PLATE = HEMISPHERE_EQUATOR_Z - T
HOLES = [
    (BR * math.cos(math.radians(a)), BR * math.sin(math.radians(a)))
    for a in P["mount_hole_angles_deg"]
]

assert 0 < F < R_ROD < R
assert STRAIGHT_LENGTH_FROM_PLATE > F
assert LAND >= 0.8 - 1e-9
assert BR - CR > R_ROD + F, "Countersink must clear the root fillet."
assert BR + CR < R
assert P["nominal_tip_tcp_xyz_mm"] == [0, 0, H]


def build():
    # Revolve an exact axial section. The first arc is the concave R2 root;
    # the second is one quarter of the R15 circle, producing a hemisphere.
    model = (
        cq.Workplane("XZ")
        .moveTo(0, 0).lineTo(R, 0).lineTo(R, T).lineTo(R_ROD + F, T)
        .threePointArc(
            (R_ROD + F - F / math.sqrt(2), T + F - F / math.sqrt(2)),
            (R_ROD, T + F),
        )
        .lineTo(R_ROD, HEMISPHERE_EQUATOR_Z)
        .threePointArc(
            (R_ROD / math.sqrt(2), HEMISPHERE_EQUATOR_Z + R_ROD / math.sqrt(2)),
            (0, H),
        )
        .close().revolve(360, (0, 0), (0, 1))
    )
    for x, y in HOLES:
        bore = cq.Solid.makeCylinder(HR, T + 2, cq.Vector(x, y, -1))
        cone = cq.Solid.makeCone(
            HR, CR + math.tan(HALF_ANGLE), SINK_DEPTH + 1,
            cq.Vector(x, y, LAND), cq.Vector(0, 0, 1),
        )
        model = model.cut(bore).cut(cone)
    return model.clean()


def export_scad():
    content = f'''// One piece: full flange plate, straight rod, hemispherical tip.
// All dimensions in mm. z=0 is the robot contact face / print bed.
// Overall length INCLUDES plate thickness. CAD has no internal cavity.
// Regenerated by build_cad.py; parameters.json is the shared parameter source.
overall_length = {H};
plate_diameter = {2*R};
plate_thickness = {T};
rod_diameter = {2*R_ROD};
root_fillet_radius = {F};
mount_pcd = {2*BR};
hole_angles = {P['mount_hole_angles_deg']};
clearance_diameter = {2*HR};
countersink_diameter = {2*CR};
countersink_angle = {P['countersink_angle_deg']};
$fn = 256;
r = rod_diameter/2;
f = root_fillet_radius;
equator_z = overall_length-r;
sink_depth = (countersink_diameter-clearance_diameter)/2/tan(countersink_angle/2);
assert(plate_thickness-sink_depth >= 0.8-0.00001);
assert(mount_pcd/2-countersink_diameter/2 > r+f);
profile = concat(
  [[0,0], [plate_diameter/2,0], [plate_diameter/2,plate_thickness], [r+f,plate_thickness]],
  [for(a=[-91:-1:-180]) [r+f+f*cos(a), plate_thickness+f+f*sin(a)]],
  [[r,equator_z]],
  [for(a=[1:1:89]) [r*cos(a),equator_z+r*sin(a)]],
  [[0,overall_length]]
);
difference() {{
  rotate_extrude(convexity=10) polygon(profile);
  for(a=hole_angles) translate([mount_pcd/2*cos(a),mount_pcd/2*sin(a),0]) {{
    translate([0,0,-1]) cylinder(h=plate_thickness+2,d=clearance_diameter);
    translate([0,0,plate_thickness-sink_depth])
      cylinder(h=sink_depth+1,d1=clearance_diameter,
               d2=countersink_diameter+2*tan(countersink_angle/2));
  }}
}}
'''
    (ROOT / f"{STEM}.scad").write_text(content)


def section_radii(mesh, z, centre=(0, 0), max_radius=None):
    section = mesh.section(plane_origin=[0, 0, z], plane_normal=[0, 0, 1])
    assert section is not None, f"Missing section at z={z}"
    loops = []
    for loop in section.discrete:
        radii = np.linalg.norm(loop[:, :2] - centre, axis=1)
        if max_radius is None or radii.max() < max_radius:
            loops.append(radii)
    return loops


def export_stl(model):
    path = ROOT / f"{STEM}.stl"
    model.val().exportStl(str(path), tolerance=0.01, angularTolerance=0.04)
    mesh = trimesh.load_mesh(path, process=True)
    # OCCT can emit a collapsed triangle where all longitudes meet at the
    # hemisphere pole. Remove only zero-area facets, then validate topology.
    keep = mesh.nondegenerate_faces(height=1e-8)
    removed = int(np.count_nonzero(~keep))
    mesh.update_faces(keep)
    mesh.remove_unreferenced_vertices()
    mesh.export(path, file_type="stl")
    return removed


def verify(model, removed_degenerate_faces):
    mesh = trimesh.load_mesh(ROOT / f"{STEM}.stl", process=True)
    solid = model.val()
    assert solid.isValid() and len(model.solids().vals()) == 1
    assert mesh.is_watertight and mesh.is_winding_consistent and mesh.is_volume
    assert mesh.body_count == 1
    assert np.allclose(mesh.bounds, [[-R, -R, 0], [R, R, H]], atol=0.005)
    # Ignore attached tessellation when checking exact CAD surface extents.
    cad_box = Bnd_Box()
    BRepBndLib.AddOptimal_s(solid.wrapped, cad_box, False, False)
    cad_bounds = np.asarray(cad_box.Get()).reshape(2,3)
    assert np.allclose(cad_bounds, [[-R,-R,0],[R,R,H]], atol=1e-5)

    # Independent volume calculation for the disk, rod, hemisphere and root.
    fillet_volume = quad(
        lambda u: math.pi * ((R_ROD + F - math.sqrt(F*F-u*u))**2 - R_ROD**2), 0, F
    )[0]
    hole_volume = math.pi * HR**2 * LAND + math.pi * SINK_DEPTH / 3 * (CR**2 + CR*HR + HR**2)
    expected_volume = (math.pi*R**2*T + math.pi*R_ROD**2*STRAIGHT_LENGTH_FROM_PLATE
                       + 2/3*math.pi*R_ROD**3 + fillet_volume - len(HOLES)*hole_volume)
    assert math.isclose(solid.Volume(), expected_volume, rel_tol=1e-7)
    assert math.isclose(mesh.volume, expected_volume, rel_tol=0.0005)
    imported = cq.importers.importStep(str(ROOT / f"{STEM}.step"))
    assert imported.val().isValid() and len(imported.solids().vals()) == 1
    assert math.isclose(imported.val().Volume(), expected_volume, rel_tol=1e-7)

    checks = []
    for z in (0.2, T - 0.2):
        expected_r = HR if z <= LAND else HR + (z - LAND)*math.tan(HALF_ANGLE)
        for centre in HOLES:
            loops = section_radii(mesh, z, centre, CR+0.05)
            assert len(loops) == 1
            error = float(np.max(np.abs(loops[0]-expected_r)))
            assert error < 0.01
            checks.append(dict(feature="mount_hole", z_mm=z, centre_xy_mm=centre,
                               expected_radius_mm=expected_r, max_error_mm=error))

    # Above the plate, each section must be exactly one closed outer contour:
    # this also rejects separate shells, unintended cavities and disconnected tips.
    for z, expected_r, feature in [
        (T+F/2, R_ROD+F-math.sqrt(F**2-(F/2)**2), "root_fillet"),
        (T+F+1, R_ROD, "shaft_base"),
        ((T+HEMISPHERE_EQUATOR_Z)/2, R_ROD, "shaft_middle"),
        (HEMISPHERE_EQUATOR_Z, R_ROD, "hemisphere_equator"),
        (HEMISPHERE_EQUATOR_Z+R_ROD/2, math.sqrt(R_ROD**2-(R_ROD/2)**2), "hemisphere_mid"),
        (H-1, math.sqrt(R_ROD**2-(R_ROD-1)**2), "hemisphere_tip"),
    ]:
        loops = section_radii(mesh, z)
        assert len(loops) == 1
        error = float(np.max(np.abs(loops[0]-expected_r)))
        assert error < 0.025, (feature, error)
        checks.append(dict(feature=feature, z_mm=z, expected_radius_mm=expected_r, max_error_mm=error))

    # Verify compatibility with the successful quarter coupon, without modifying it.
    coupon = json.loads((ROOT.parent / "flange_quarter_m6x8" / "parameters.json").read_text())
    assert R == coupon["outer_radius_mm"] and T == coupon["thickness_mm"]
    for key in ("clearance_diameter_mm", "countersink_diameter_mm", "countersink_angle_deg", "screw_overall_length_mm"):
        assert P[key] == coupon[key]
    assert 2*BR == coupon["bolt_circle_diameter_mm"]

    report = dict(
        units="mm", cad_valid=True, solid_count=1, step_roundtrip_valid=True,
        stl_watertight=bool(mesh.is_watertight), stl_winding_consistent=bool(mesh.is_winding_consistent),
        stl_body_count=int(mesh.body_count), triangles=len(mesh.faces), bounds_mm=mesh.bounds.tolist(),
        removed_zero_area_stl_faces=removed_degenerate_faces,
        size_mm=mesh.extents.tolist(), overall_length_from_flange_contact_face_mm=H,
        exact_cad_bounds_mm=cad_bounds.tolist(),
        projection_above_plate_mm=H-T, straight_length_from_plate_to_equator_mm=STRAIGHT_LENGTH_FROM_PLATE,
        tip_hemisphere_radius_mm=R_ROD, tip_hemisphere_equator_z_mm=HEMISPHERE_EQUATOR_Z,
        root_fillet_radius_mm=F, hole_centres_xy_mm=HOLES, countersink_depth_mm=SINK_DEPTH,
        straight_bore_land_mm=LAND, countersink_to_root_min_clearance_mm=BR-CR-R_ROD-F,
        screw_protrusion_if_head_flush_mm=P["screw_overall_length_mm"]-T,
        quarter_coupon_dimensions_preserved=True, cad_volume_mm3=solid.Volume(),
        analytic_volume_mm3=expected_volume, stl_volume_mm3=float(mesh.volume),
        p1s_default_height_limit_mm=250, p1s_height_margin_mm=250-H,
        build_orientation="Plate underside on bed; shaft vertical +Z; no support geometry required.",
        cross_section_checks=checks,
        scope="Geometry verified. Four-hole printed fit, screwdriver access and mechanical strength need physical confirmation. No slicing or robot motion performed.",
    )
    (ROOT / "geometry_checks.json").write_text(json.dumps(report, indent=2)+"\n")
    print(json.dumps({key: report[key] for key in ["size_mm", "cad_valid", "solid_count", "stl_watertight",
        "step_roundtrip_valid", "triangles", "cad_volume_mm3", "p1s_height_margin_mm",
        "quarter_coupon_dimensions_preserved"]}, indent=2))
    return mesh


def dimension(ax, start, end, label, offset=(0,0), rotation=0):
    ax.annotate("", xy=end, xytext=start, arrowprops=dict(arrowstyle="<->",color="#29485f",lw=1))
    mid = (np.asarray(start)+np.asarray(end))/2+offset
    ax.text(*mid, label, ha="center",va="center",rotation=rotation,fontsize=10,color="#17314b",
            bbox=dict(facecolor="#f7f9fc",edgecolor="none",pad=1.5))


def preview(mesh):
    bg, ink, fill = "#f7f9fc", "#17314b", "#cfe3ee"
    fig = plt.figure(figsize=(14,9), facecolor=bg)
    gs = fig.add_gridspec(2,3, left=0.015,right=0.98,top=0.86,bottom=0.13,
                          width_ratios=[1.15,0.85,1.05],height_ratios=[1,0.75],wspace=0.15,hspace=0.2)
    fig.text(0.035,0.94,"xArm flange + rounded rod",fontsize=25,weight="bold",color=ink)
    fig.text(0.035,0.895,f"TOTAL {H:g} mm from robot flange contact face  |  rod Ø{2*R_ROD:g}  |  PETG  |  one piece",fontsize=12,color="#547187")

    ax = fig.add_subplot(gs[:,0], projection="3d",facecolor=bg)
    light = np.array([-0.5,-0.6,0.8]); light /= np.linalg.norm(light)
    shades = 0.48+0.52*np.clip(mesh.face_normals@light,0,1)
    colors = shades[:,None]*np.array([0.36,0.64,0.79])
    elev, azim = math.radians(16), math.radians(-58)
    camera = np.array([math.cos(elev)*math.cos(azim),math.cos(elev)*math.sin(azim),math.sin(elev)])
    visible = mesh.face_normals@camera > 1e-9
    ax.add_collection3d(Poly3DCollection(mesh.triangles[visible],facecolors=colors[visible],
                                        edgecolors="none",linewidths=0,antialiased=False))
    ax.set_xlim(-R,R); ax.set_ylim(-R,R); ax.set_zlim(0,H)
    ax.set_box_aspect((2*R,2*R,H)); ax.view_init(elev=16,azim=-58); ax.set_proj_type("ortho")
    ax.set_axis_off()

    side = fig.add_subplot(gs[:,1],facecolor=bg)
    positive = [(R,0),(R,T),(R_ROD+F,T)]
    positive += [(R_ROD+F+F*math.cos(a),T+F+F*math.sin(a)) for a in np.linspace(-math.pi/2,-math.pi,24)[1:]]
    positive += [(R_ROD,HEMISPHERE_EQUATOR_Z)]
    positive += [(R_ROD*math.cos(a),HEMISPHERE_EQUATOR_Z+R_ROD*math.sin(a)) for a in np.linspace(0,math.pi/2,60)[1:]]
    outline = positive + [(-x,z) for x,z in positive[-2::-1]]
    side.add_patch(Polygon(outline,fc=fill,ec=ink,lw=1.2))
    side.plot([0,0],[-5,H+4],ls="--",lw=0.6,color="#8c9bab")
    side.plot([-R-14,R+34],[0,0],color="#9aaab5",lw=0.7)
    side.plot([-R-14,0],[H,H],color="#9aaab5",lw=0.7)
    side.plot([R_ROD,R+18],[T,T],color="#9aaab5",lw=0.7)
    side.plot([R_ROD,R+18],[HEMISPHERE_EQUATOR_Z,HEMISPHERE_EQUATOR_Z],color="#9aaab5",lw=0.7)
    dimension(side,(-R-10,0),(-R-10,H),f"{H:g} total",rotation=90)
    dimension(side,(R+12,T),(R+12,HEMISPHERE_EQUATOR_Z),f"{STRAIGHT_LENGTH_FROM_PLATE:g} straight",rotation=90)
    dimension(side,(-R_ROD,0.62*H),(R_ROD,0.62*H),f"Ø{2*R_ROD:g}")
    dimension(side,(-R,-10),(R,-10),f"Ø{2*R:g}")
    side.annotate(f"R{R_ROD:g} hemisphere",xy=(R_ROD/math.sqrt(2),HEMISPHERE_EQUATOR_Z+R_ROD/math.sqrt(2)),
                  xytext=(-R-2,H+12),fontsize=10,color=ink,arrowprops=dict(arrowstyle="-",color=ink))
    side.text(-R-13,-22,"Robot contact face = z0",fontsize=9,color=ink)
    side.set_aspect("equal"); side.set_xlim(-R-21,R+25);side.set_ylim(-25,H+23);side.axis("off")
    side.set_title("SIDE VIEW / mm",loc="left",fontsize=11,weight="bold",color=ink,pad=8)

    top = fig.add_subplot(gs[0,2],facecolor=bg)
    top.add_patch(Circle((0,0),R,fc=fill,ec=ink,lw=1.3))
    top.add_patch(Circle((0,0),BR,fill=False,ec="#8c9bab",ls="--",lw=0.7))
    top.add_patch(Circle((0,0),R_ROD+F,fc="#adc9db",ec=ink,lw=0.7))
    top.add_patch(Circle((0,0),R_ROD,fc="#70a4c1",ec=ink,lw=1.0))
    for x,y in HOLES:
        top.add_patch(Circle((x,y),CR,fc="#a9c4d7",ec=ink,lw=0.8))
        top.add_patch(Circle((x,y),HR,fc=bg,ec=ink,lw=0.8))
    top.annotate(f"PCD {2*BR:g}",xy=(BR,0),xytext=(R+4,0),fontsize=10,color=ink,
                 arrowprops=dict(arrowstyle="-",color=ink))
    top.set_aspect("equal");top.set_xlim(-R-4,R+28);top.set_ylim(-R-8,R+7);top.axis("off")
    top.set_title("FULL FLANGE / 4 M6 COUNTERSINKS",loc="left",fontsize=11,weight="bold",color=ink)

    detail = fig.add_subplot(gs[1,2],facecolor=bg)
    detail.axis("off")
    detail.text(0,1,"MATCHES THE SUCCESSFUL FIT COUPON",va="top",fontsize=11,weight="bold",color=ink)
    detail.text(0,0.83,
        f"Plate: Ø{2*R:g} x {T:g} mm\n"
        f"4 x Ø{2*HR:g} through holes\n"
        f"Countersinks: Ø{2*CR:g} / {P['countersink_angle_deg']:g}°\n"
        f"Rod root blend: R{F:g}\n\n"
        f"Projection above plate: {H-T:g} mm\n"
        f"P1S height margin: {250-H:g} mm\n"
        f"Mounting screws: M6 x 8 Phillips",
        va="top",fontsize=12,color=ink,linespacing=1.65)
    fig.text(0.035,0.045,"Print upright: flat plate face DOWN, tip UP. Length includes the 4 mm plate. Geometry verified; physical load capacity untested.",
             fontsize=10,color="#547187")
    fig.savefig(ROOT / "preview.png",dpi=170,facecolor=bg)
    plt.close(fig)


if __name__ == "__main__":
    part = build()
    cq.exporters.export(part,str(ROOT / f"{STEM}.step"))
    removed = export_stl(part)
    export_scad()
    preview(verify(part, removed))
